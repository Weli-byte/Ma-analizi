"""Coverage report and leakage self-check of the xG observations (ADR 0085).

`python -m src.xg.report --root <checkout holding artifacts/stats/highlightly> --as-of 2026-10-27T00:00:00Z --out docs/xg/sprint07_xg_coverage.md [--observations-out PATH]`

The report is a function of the stored data and `--as-of`; running it twice on the same data gives the same file. It states what the data can and cannot support: the earliest time any xG
was available to us, how many matches were observed, and how many would have been usable at the cutoff of an earlier prediction (none before the first fetch).
"""

import argparse
import statistics
from collections import Counter, defaultdict
from dataclasses import replace
from datetime import UTC, datetime, timedelta
from pathlib import Path

from src.cli_utils import configure_output
from src.config import config_dir_for
from src.data.teams import TeamDirectory

from .features import MIN_OBS, fixture_features
from .observations import MISSING_XG, NO_STATISTICS, OBSERVED, Observation, digest, load, write_jsonl

REPO = Path(__file__).resolve().parents[2]
MIN_MATCHES_FOR_ABLATION = 1500   # pre-registered (ADR 0085): matches with complete as-of xG features before a +xG ablation is run at all
MIN_PER_LEAGUE_FOR_LEAGUE_CLAIM = 150


def leakage_check(obs: list[Observation], limit: int = 200) -> dict:
    """For observed matches: features at kickoff - 90 min must not contain the match itself nor any row fetched after that cutoff."""
    checked = bad_self = bad_future = 0
    for o in [x for x in obs if x.coverage_status == OBSERVED][-limit:]:
        cutoff = o.kickoff_utc - timedelta(minutes=90)
        full = fixture_features(obs, o.home_id, o.away_id, cutoff, o.fixture_key, force=True)
        known = [x if (x.available_at_utc is None or x.available_at_utc <= cutoff) else replace(x, xg_home=None, xg_away=None, ingested_at_utc=None, available_at_utc=None, coverage_status=NO_STATISTICS) for x in obs]
        without_future = fixture_features(known, o.home_id, o.away_id, cutoff, o.fixture_key, force=True)  # same matches, but the xG fetched after the cutoff blanked out
        checked += 1
        if o.available_at_utc is not None and o.available_at_utc <= cutoff:
            bad_self += 1   # the match's own xG was fetched before its own cutoff: impossible for a finished match, flagged if it ever happens
        for side in ("home", "away"):
            for k, v in full[side].items():
                w = without_future[side][k]
                if k not in ("last_available_at",) and not ((v != v and w != w) or v == w):
                    bad_future += 1
    return {"checked": checked, "own_row_available_before_own_cutoff": bad_self, "future_rows_changed_a_feature": bad_future}


def build(obs: list[Observation], rep: dict, as_of: datetime) -> str:
    seen = [o for o in obs if o.kickoff_utc + timedelta(hours=3) <= as_of]
    by = defaultdict(Counter)
    for o in seen:
        by[(o.competition_id, o.season)][o.coverage_status] += 1
    avail = [o.available_at_utc for o in obs if o.available_at_utc is not None]
    observed = [o for o in obs if o.coverage_status == OBSERVED]
    late = [o for o in observed if o.available_at_utc - o.kickoff_utc > timedelta(days=2)]
    per_team: Counter = Counter()
    for o in observed:
        per_team[o.home_id] += 1
        per_team[o.away_id] += 1
    ready = sum(1 for n in per_team.values() if n >= MIN_OBS)
    leak = leakage_check(obs)
    complete = 0
    for o in observed:
        f = fixture_features(obs, o.home_id, o.away_id, o.kickoff_utc - timedelta(minutes=90), o.fixture_key, force=True)
        complete += 1 if f["home"]["xg_available"] and f["away"]["xg_available"] else 0
    lines = [
        "# Sprint 7 - xG coverage and as-of report (ADR 0085)", "",
        f"As of {as_of.isoformat()} · source `highlightly` (statistics store, ADR 0050) · data digest `{digest(obs)[:16]}` · generated by `python -m src.xg.report`.", "",
        "## What the data is",
        f"- Finished matches read: {rep['finished']} (rows read {rep['rows_read']}); unique matches kept: {len(obs)}; duplicate rows: {rep['duplicates']}; unresolved clubs: {len(rep['unresolved_clubs'])} ({', '.join(rep['unresolved_clubs']) or 'none'}; their matches are left out, never guessed); invalid xG values: {rep['invalid_xg']}.",
        f"- Observed (both xG values present): **{len(observed)}**. Statistics present but no xG: {sum(1 for o in obs if o.coverage_status == MISSING_XG)}. No statistics fetched yet: {sum(1 for o in obs if o.coverage_status == NO_STATISTICS)}.",
        f"- The provider gives no publication time. The xG of a match is usable as history only from the moment we fetched it: first {min(avail).isoformat() if avail else 'n/a'}, last {max(avail).isoformat() if avail else 'n/a'}.",
        f"- {len(late)} of {len(observed)} observed matches were fetched more than two days after kick-off: a prediction cutoff before the fetch cannot use them, so **no backtest on earlier dates is possible with this data**; the history grows only prospectively.", "",
        "## Coverage by league and season (finished matches)", "",
        "| league | season | finished | observed xG | missing xG | no statistics | observed % |", "|---|---|---|---|---|---|---|",
    ]  # fmt: skip
    for (lg, season), c in sorted(by.items()):
        n = sum(c.values())
        lines.append(f"| {lg} | {season}-{str(season + 1)[2:]} | {n} | {c[OBSERVED]} | {c[MISSING_XG]} | {c[NO_STATISTICS]} | {100 * c[OBSERVED] / n:.1f} |")
    counts = sorted(per_team.values())
    lines += ["", "## Per-team observations", "",
              f"- Teams with at least one observed match: {len(per_team)}; with at least {MIN_OBS} (feature available): **{ready}**; median observations per team: {statistics.median(counts) if counts else 0}; max {max(counts, default=0)}.", "",
              "## Leakage self-check (automatic)", "",
              f"- Observed matches checked: {leak['checked']}; own xG available before the own cutoff: {leak['own_row_available_before_own_cutoff']}; features changed by rows fetched after the cutoff: {leak['future_rows_changed_a_feature']} (both must be 0).", "",
              "## Decision gate for a +xG ablation (pre-registered)", "",
              f"- A baseline versus +xG ablation on 1X2 / over-under / BTTS is run only with at least {MIN_MATCHES_FOR_ABLATION} matches that have complete as-of xG features for both teams, and a league-level claim only with {MIN_PER_LEAGUE_FOR_LEAGUE_CLAIM} such matches in that league.",
              f"- Matches with complete as-of xG features for both clubs at kick-off minus 90 minutes: **{complete}**. Gate: **{'OPEN' if complete >= MIN_MATCHES_FOR_ABLATION else 'NOT MET - ablation not run'}**.",
              "- `XG_FEATURES_ENABLED` stays unset (OFF): no model reads an xG feature.", ""]  # fmt: skip
    return "\n".join(lines)


def main(argv=None) -> int:
    configure_output()
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=str(REPO), help="checkout that holds artifacts/stats/highlightly")
    ap.add_argument("--as-of", default=None, help="UTC time of the report (default: now)")
    ap.add_argument("--out", default=None, help="markdown file to write (default: print)")
    ap.add_argument("--observations-out", default=None, help="write the observations as JSONL (deterministic)")
    a = ap.parse_args(argv)
    as_of = datetime.fromisoformat(a.as_of.replace("Z", "+00:00")) if a.as_of else datetime.now(UTC)
    directory = TeamDirectory.load(config_dir_for(REPO) / "team_aliases.yaml")
    obs, rep = load(Path(a.root), directory)
    text = build(obs, rep, as_of)
    if a.observations_out:
        write_jsonl(obs, Path(a.observations_out))
    if a.out:
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text(text + "\n", encoding="utf-8", newline="\n")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
